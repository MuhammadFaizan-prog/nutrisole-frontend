#!/usr/bin/env python3
"""G9 Stage J4: extract per-100 g nutrition for the five showcase classes from the official USDA FoodData Central
SR Legacy CSV release, and write native/src/cv/data/nutritionFdc.ts (generated; do not hand-edit values).

Source: https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip
        (downloaded 2026-10-15; sha256 recorded below and in the generated file). Food pages: https://fdc.nal.usda.gov/food-details/<fdc_id>/nutrients
Nothing is estimated: a nutrient absent from the release is written as missing. Glycemic index is not in FDC and stays missing.
Usage: python3 j4_nutrition_extract.py --zip FoodData_Central_sr_legacy_food_csv_2018-04.zip [--out ../../../../../native/src/cv/data/nutritionFdc.ts]
"""
import argparse, csv, hashlib, io, json, zipfile
from pathlib import Path

ZIP_URL = "https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip"
ZIP_SHA256 = "b80817294b8850530aaedf2e515c02593b1824f763a0ff356e5c2081643e6fd0"
FOODS = {  # showcase class -> (fdc_id, match note)
    "apple": ("171688", "raw apple with skin"),
    "banana": ("173944", "raw banana"),
    "citrus_orange": ("169097", "raw orange, all commercial varieties; kinnow/malta are not separate FDC SR Legacy foods, so this is the closest sourced match"),
    "tomato": ("170457", "raw red ripe tomato, year-round average"),
    "carrot": ("170393", "raw carrot"),
}
NUTRIENTS = {  # key -> (FDC nutrient id, unit)
    "energy_kcal": ("1008", "kcal"), "water_g": ("1051", "g"), "protein_g": ("1003", "g"), "fat_g": ("1004", "g"),
    "carbohydrate_g": ("1005", "g"), "fiber_g": ("1079", "g"), "sugars_g": ("2000", "g"), "potassium_mg": ("1092", "mg"),
    "vitamin_c_mg": ("1162", "mg"),
}
PORTIONS = {"apple": "medium", "banana": "medium", "citrus_orange": "fruit", "tomato": "medium whole", "carrot": "medium"}
DEFAULT_OUT = Path(__file__).resolve().parents[5] / "native/src/cv/data/nutritionFdc.ts"


def extract(zip_bytes):
    if hashlib.sha256(zip_bytes).hexdigest() != ZIP_SHA256: raise SystemExit("FDC zip sha256 differs from the recorded release")
    z = zipfile.ZipFile(io.BytesIO(zip_bytes))
    rd = lambda n: csv.DictReader(io.TextIOWrapper(z.open(next(x for x in z.namelist() if x.endswith("/" + n))), encoding="utf-8"))
    ids = {v[0]: k for k, v in FOODS.items()}
    food = {r["fdc_id"]: r for r in rd("food.csv") if r["fdc_id"] in ids}
    nid = {v[0]: k for k, v in NUTRIENTS.items()}
    vals = {k: {} for k in FOODS}
    for r in rd("food_nutrient.csv"):
        if r["fdc_id"] in ids and r["nutrient_id"] in nid: vals[ids[r["fdc_id"]]][nid[r["nutrient_id"]]] = float(r["amount"])
    por = {k: None for k in FOODS}
    for r in rd("food_portion.csv"):
        k = ids.get(r["fdc_id"])
        if k and r["modifier"].startswith(PORTIONS[k]) and por[k] is None:
            por[k] = dict(label=f"{float(r['amount']):g} {r['modifier']}", grams=float(r["gram_weight"]))
    out = {}
    for k, (fid, note) in FOODS.items():
        out[k] = dict(fdcId=int(fid), description=food[fid]["description"], publicationDate=food[fid]["publication_date"], matchNote=note,
                      nutrients={n: vals[k].get(n) for n in NUTRIENTS}, portion=por[k])
    return out


def to_ts(data):
    lines = ["// GENERATED by ml/runs/G9/stageJ/scripts/j4_nutrition_extract.py from the official USDA FoodData Central SR Legacy release.",
             f"// Source zip: {ZIP_URL} (sha256 {ZIP_SHA256}). Do not hand-edit values; re-run the script.",
             "// Values are per 100 g of the raw edible portion. null = not present in the source (treated as missing, never estimated).",
             f"export const FDC_SOURCE = {json.dumps(dict(name='USDA FoodData Central', dataset='SR Legacy (April 2018 release)', datasetUrl=ZIP_URL, datasetSha256=ZIP_SHA256, retrieved='2026-10-15'))} as const;",
             f"export const NUTRIENT_UNITS = {json.dumps({k: u for k, (_, u) in NUTRIENTS.items()})} as const;",
             f"export const FDC_NUTRIENT_IDS = {json.dumps({k: int(i) for k, (i, _) in NUTRIENTS.items()})} as const;",
             f"export const FDC_SHOWCASE = {json.dumps(data, indent=1, ensure_ascii=False)} as const;", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--zip", required=True); ap.add_argument("--out", default=str(DEFAULT_OUT))
    a = ap.parse_args()
    d = extract(Path(a.zip).read_bytes())
    Path(a.out).write_text(to_ts(d), encoding="utf-8"); print(json.dumps(d, indent=1))
