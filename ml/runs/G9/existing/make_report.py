"""Collect G9 existing-models results into results_autogen.md + summary.json (reads only files in this folder)."""
import json
import os

H = os.path.dirname(os.path.abspath(__file__))
M = ["g3", "snapml", "calories"]
LAB = {"g3": "G3 control (yolo11n@480)", "snapml": "snapml veggies-and-fruits-balanced v1", "calories": "calories fruits-and-veg-2 v2"}
NAMES = ["banana", "apple", "mango", "citrus", "guava", "pomegranate", "lemon_lime", "tomato", "potato", "cucumber", "carrot", "capsicum"]


def load(p):
    p = os.path.join(H, p)
    return json.load(open(p)) if os.path.exists(p) else None


def f(v, n=3):
    return "n/a" if v is None else (f"{v:.{n}f}" if isinstance(v, float) else str(v))


out, summ = [], {}
out.append("# G9 existing models vs G3: DEV results (autogenerated by make_report.py)\n")
out.append("All numbers are DEV only (synthetic g3clips_dev det + dev-neg clips, VB8 dev/dev_v7 web clips, G3 val n=402). "
           "No holdout, no locked test split. CPU = sandbox 2 vCPU, onnxruntime, 2 threads (not a phone).\n")
# 1. synthetic gauntlet
out.append("## 1. Synthetic DEV clips through ml/eval/video_gauntlet.py (fixed-frame stride 2, guard minArea 0.01, rule 2 off, no classifier)\n")
out.append("| model | det frame_acc | det segment_acc (n=24) | never-correct segs | TTFC p50 ms | TTFC p90 ms | neg FA/min | neg FA episodes/min | det latency p50 / p95 ms |")
out.append("|---|---|---|---|---|---|---|---|---|")
pc_rows = {}
for m in M:
    gd, gn = load(f"gauntlet_dev/{m}_det/gauntlet.json"), load(f"gauntlet_dev/{m}_neg/gauntlet.json")
    g = dict(clips=dict(det=gd["clips"]["det"], neg=gn["clips"]["neg"]), latency_overall=gd["latency_overall"]) if gd and gn else None
    if not g:
        out.append(f"| {LAB[m]} | not run | | | | | | | |"); continue
    d, n = g["clips"].get("det", {}), g["clips"].get("neg", {})
    lat = g["latency_overall"]["det_ms"]
    out.append(f"| {LAB[m]} | {f(d.get('frame_acc'))} | {f(d.get('segment_acc'))} | {d.get('never_correct_segments')} | {f(d['ttfc_ms']['p50'],0)} | {f(d['ttfc_ms']['p90'],0)} | "
               f"{f(n.get('false_alarms_per_min'),2)} | {f(n.get('fa_episodes_per_min'),2)} | {f(lat['p50'],0)} / {f(lat['p95'],0)} |")
    pc_rows[m] = d.get("per_class_recall", {})
    summ[f"gauntlet_{m}"] = dict(frame_acc=d.get("frame_acc"), segment_acc=d.get("segment_acc"), never_correct=d.get("never_correct_segments"),
                                 ttfc=d.get("ttfc_ms"), fa_min=n.get("false_alarms_per_min"), fa_ep_min=n.get("fa_episodes_per_min"), det_ms=lat, per_class=d.get("per_class_recall"))
cls_present = [c for c in NAMES if any(c in pc_rows.get(m, {}) for m in M)]
out.append("\nPer-class frame recall on the det clip (n frames):\n")
out.append("| class | n | " + " | ".join(LAB[m] for m in M) + " |")
out.append("|---|---|" + "---|" * len(M))
for c in cls_present:
    nn = next((pc_rows[m][c]["n"] for m in M if c in pc_rows.get(m, {})), "")
    out.append(f"| {c} | {nn} | " + " | ".join(f(pc_rows.get(m, {}).get(c, {}).get("recall")) for m in M) + " |")
# 2. VB8 dev
out.append("\n## 2. VB8 DEV web clips (splits_v7 dev + dev_v7, 28 clips), 2 fps replay, conf 0.35, same guard. No box GT: descriptive + weak title check\n")
out.append("| model | sampled frames | frames with any box | title-expected clips: mean frac frames with expected class | title clips: frames with an off-title class | chilli-title clips: frames with 'capsicum' | latency p50 / p95 ms |")
out.append("|---|---|---|---|---|---|---|")
vb = {}
for m in M:
    v = load(f"vb8dev/vb8dev_{m}.json")
    if not v:
        out.append(f"| {LAB[m]} | not run | | | | | |"); continue
    vb[m] = v
    cl = v["clips"].values()
    tot = sum(c.get("sampled_frames", 0) for c in cl); anyf = sum(c.get("frames_any", 0) for c in cl)
    te = [c for c in cl if c.get("title_expect")]
    hit = sum(c["title_hit_frac"] for c in te) / max(1, len(te)); off = sum(c["off_title_frames"] for c in te)
    chil = sum(sum(1 for _, ds in c["per_frame"] if any(d[0] == "capsicum" for d in ds)) for c in cl if c.get("chilli_title"))
    chil_n = sum(c["sampled_frames"] for c in cl if c.get("chilli_title"))
    out.append(f"| {LAB[m]} | {tot} | {anyf} ({anyf/max(1,tot):.2f}) | {hit:.3f} (n={len(te)} clips) | {off} | {chil}/{chil_n} | {f(v['latency_ms']['p50'],0)} / {f(v['latency_ms']['p95'],0)} |")
    summ[f"vb8dev_{m}"] = dict(sampled=tot, frames_any=anyf, title_hit_mean=round(hit, 4), off_title_frames=off, chilli_capsicum_frames=chil, chilli_frames=chil_n, latency=v["latency_ms"])
if vb:
    out.append("\nPer-class frames-with-detection summed over the 28 dev clips:\n")
    out.append("| class | " + " | ".join(LAB[m] for m in M if m in vb) + " |")
    out.append("|---|" + "---|" * len(vb))
    for c in NAMES:
        out.append(f"| {c} | " + " | ".join(str(sum(cc.get("class_frames", {}).get(c, 0) for cc in vb[m]["clips"].values())) for m in M if m in vb) + " |")
    out.append("\nPer title-expected clip (fraction of sampled frames showing the expected class):\n")
    out.append("| clip | expected | " + " | ".join(m for m in M if m in vb) + " |")
    out.append("|---|---|" + "---|" * len(vb))
    for cid, c in vb[next(iter(vb))]["clips"].items():
        if c.get("title_expect"):
            out.append(f"| {cid} | {'+'.join(c['title_expect'])} | " + " | ".join(f(vb[m]['clips'][cid].get('title_hit_frac')) for m in M if m in vb) + " |")
    for m in ["snapml", "calories"]:
        if m in vb:
            u = {}
            for cc in vb[m]["clips"].values():
                for k, n in cc.get("unmapped_src_dets", {}).items():
                    u[k] = u.get(k, 0) + n
            out.append(f"\n{LAB[m]} out-of-taxonomy (ignored) detections on dev clips: " + ", ".join(f"{k} {n}" for k, n in sorted(u.items(), key=lambda t: -t[1])))
# 3. still
out.append("\n## 3. Still images, G3 VAL (det_v3 val.txt n=402), AP50 per mapped class (same evaluator for all)\n")
for sub in ["all", "non_oiv7"]:
    out.append(f"\nSubset `{sub}`" + (" (345 images; excludes 57 OIV7 val images that snapml may have trained on)" if sub == "non_oiv7" else " (402; OIV7 rows are leak-risk for snapml)") + ":\n")
    out.append("| class | npos | " + " | ".join(LAB[m] for m in M) + " |")
    out.append("|---|---|" + "---|" * len(M))
    S = {m: load(f"still/val_{m}.json") for m in M}
    for c in NAMES:
        npos = next((S[m]["subsets"][sub][c]["npos"] for m in M if S[m]), "")
        out.append(f"| {c} | {npos} | " + " | ".join(f(S[m]["subsets"][sub][c]["ap50"]) if S[m] else "not run" for m in M) + " |")
    for m in M:
        if S[m]:
            summ.setdefault(f"still_{m}", {})[sub] = {c: S[m]["subsets"][sub][c]["ap50"] for c in NAMES}
open(os.path.join(H, "results_autogen.md"), "w").write("\n".join(out) + "\n")
json.dump(summ, open(os.path.join(H, "summary.json"), "w"), indent=1)
print("\n".join(out))

# 4. G9 addendum: raw vs tracked, DEV-tuned thresholds, wrong-class vs missing
rt = load("raw_tracked_dev.json")
tags = (load("neg_dev_tags.json") or {}).get("tags", {})
add = ["\n## 4. Raw detector vs after tracking (identical frames: synthetic DEV det + neg clips, stride 2; IoU 0.5; same GT)\n",
       f"DEV threshold rule (pre-registered in raw_score.py): max raw correct-frame rate s.t. raw neg false boxes/min <= G3@0.35 ({rt['fa_cap_boxes_per_min'] if rt else 'n/a'}).\n",
       "| model | conf | RAW correct | RAW wrong-class | RAW missing | RAW uncovered class | RAW correct rate (all / covered) | wrong-class detections | background boxes (det clip) | RAW neg false boxes/min | TRACKED frame_acc | TRACKED segment_acc | never-correct segs | TTFC p50 ms | TRACKED neg FA/min |",
       "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
if rt:
    for m in M:
        v = rt["models"].get(m, {})
        if "sweep" not in v:
            continue
        for lab, t, trk in [("prod 0.35", 0.35, v["tracked_at_035"]), (f"DEV-tuned {v['tuned_thr']}", v["tuned_thr"], v["tracked_at_tuned"])]:
            s = next(x for x in v["sweep"] if x["det"]["thr"] == t); d, n = s["det"], s["neg"]
            add.append(f"| {LAB[m]} | {lab} | {d['correct']} | {d['wrong']} | {d['missing']} | {d['uncovered']} | {d['correct_rate']:.3f} / {d['correct_rate_covered']:.3f} | {d['wrong_class_detections']} | {d['background_boxes']} | {n['false_boxes_per_min']} | "
                       f"{trk['det']['frame_acc']} | {trk['det']['segment_acc']} | {trk['det']['never_correct_segments']} | {f(trk['det']['ttfc_ms']['p50'],0)} | {trk['neg']['false_alarms_per_min']} |")
    add.append("\nTop wrong-class pairs (GT->predicted, raw boxes) and neg false boxes by DEV tag (agent-tagged contact sheet, neg_dev_tags.json):\n")
    add.append("| model | conf | wrong-class pairs | neg FA by tag (people/clothing, signs/text, packaging, synthetic texture, outdoor) | neg FA by class |")
    add.append("|---|---|---|---|---|")
    for m in M:
        v = rt["models"].get(m, {})
        if "sweep" not in v:
            continue
        for t in sorted({0.35, v["tuned_thr"]}):
            s = next(x for x in v["sweep"] if x["det"]["thr"] == t); bs = s["neg"]["by_source"]
            tg = {k: sum(bs.get(x, 0) for x in L) for k, L in tags.items()}
            add.append(f"| {LAB[m]} | {t} | " + ", ".join(f"{k} {n}" for k, n in s["det"]["wrong_pairs"].items()) + f" | {tg.get('people_clothing')}, {tg.get('signs_text')}, {tg.get('packaging_indoor_objects')}, {tg.get('synthetic_texture')}, {tg.get('outdoor_scene_animal_vehicle')} | {s['neg']['per_class']} |")
    add.append("\nRaw sweep (correct rate / neg false boxes per min):\n")
    add.append("| conf | " + " | ".join(LAB[m] for m in M if "sweep" in rt["models"].get(m, {})) + " |")
    add.append("|---|" + "---|" * sum(1 for m in M if "sweep" in rt["models"].get(m, {})))
    for i, t in enumerate(rt["models"]["g3"]["sweep"]):
        add.append(f"| {t['det']['thr']} | " + " | ".join(f"{rt['models'][m]['sweep'][i]['det']['correct_rate']:.3f} / {rt['models'][m]['sweep'][i]['neg']['false_boxes_per_min']}" for m in M if "sweep" in rt["models"].get(m, {})) + " |")
    # VB8 dev at DEV-tuned thresholds (raw boxes, guard minArea 0.01)
    add.append("\nVB8 DEV web clips at each model's DEV-tuned threshold (raw boxes >= conf, area >= 1% of frame):\n")
    add.append("| model | conf | title clips: mean frac frames with expected class | title clips: frames with off-title class | chilli-title clips: frames with capsicum | market/mixed clips: frames with any box |")
    add.append("|---|---|---|---|---|---|")
    MARKET = ["c8ddc4768", "cf3d00ee1", "c018de016", "cfb66f6d2", "cea174b05", "c237ace91", "c3d1561b2", "ce3fc202a", "cec084f0c", "c61f2d4b9"]
    for m in M:
        v = load(f"vb8dev/vb8dev_{m}.json"); t = rt["models"].get(m, {}).get("tuned_thr")
        if not v or t is None or "raw_frames_conf01" not in next(iter(v["clips"].values())):
            continue
        hits, off, chil, chn, mk, mkn = [], 0, 0, 0, 0, 0
        for cid, c in v["clips"].items():
            fr = [[NAMES[b[0]] for b in bs if b[1] >= t and (b[4] - b[2]) * (b[5] - b[3]) >= 0.01] for _, bs in c["raw_frames_conf01"]]
            if c.get("title_expect"):
                hits.append(sum(1 for x in fr if any(y in c["title_expect"] for y in x)) / max(1, len(fr)))
                off += sum(1 for x in fr if any(y not in c["title_expect"] for y in x))
            if c.get("chilli_title"):
                chil += sum(1 for x in fr if "capsicum" in x); chn += len(fr)
            if cid in MARKET:
                mk += sum(1 for x in fr if x); mkn += len(fr)
        add.append(f"| {LAB[m]} | {t} | {sum(hits)/max(1,len(hits)):.3f} | {off} | {chil}/{chn} | {mk}/{mkn} |")
open(os.path.join(H, "results_autogen.md"), "a").write("\n".join(add) + "\n")
print("\n".join(add))
