#!/usr/bin/env python3
"""G7: assemble every machine-produced G7 result into docs/cv/gauntlet/G7_results_autogen.md (re-runnable; missing pieces are
printed as 'pending'). Narrative/decisions live in G7.md; this file is the numeric appendix it cites."""
import json, os, glob, csv
R = "/workspace/work/nutrisole/ml/runs/G7"; OUT = "/workspace/work/nutrisole/docs/cv/gauntlet/G7_results_autogen.md"
def J(p):
    try: return json.load(open(p if p.startswith("/") else f"{R}/{p}"))
    except Exception: return None
o = ["# G7 results appendix (auto-generated by ml/runs/G7/scripts/g7_report.py)", "",
     "Every number states split / n / model / imgsz / device. Nothing here is phone, emulator, Lahore or human-graded. 'pending' = the job had not finished when this file was generated.", ""]
# 1 detector tables
o += ["## A. Detector arms (strict + pooled, CPU eval)", ""]
t = f"{R}/tables.md"
o += [open(t).read() if os.path.exists(t) else "pending", ""]
T = J("tables.json")
if T:
    o += ["Strict rule check (prereg section 2 rules 1-2; per-class drop > 0.02 on test_rf / test_oiv7 / test_oiv7c for classes with >= 20 instances):", ""]
    for k, v in T.get("strict", {}).items():
        o.append(f"- {k}: pooled {v.get('pooled')} (> 0.314: {v.get('pooled_gt_g3')}), image rule pass {v.get('image_pass')}, per-class fails {v.get('per_class_fails')}")
    o.append("")
# 2 bootstrap
B = J("bootstrap_det.json")
o += ["## B. Bootstrap 95% CIs (percentile, B=1000, seed 0; recording/capture-level units)", ""]
if B:
    o.append(B.get("method", "")); o.append("")
    o += ["| split | n img | units | model | mAP50 [95% CI] | diff vs G3 [95% CI] |", "|---|---|---|---|---|---|"]
    for sp, row in B["splits"].items():
        for m, v in row["models"].items():
            d = v.get("diff_vs_ref_mAP50")
            o.append(f"| {sp} | {row['n_images']} | {row['units']} | {m} | {v['mAP50']} {v.get('mAP50_ci95')} | " + (f"{d['point']} {d.get('ci95')}" if d else "-") + " |")
else:
    o.append("pending")
o.append("")
# 3 guava
o += ["## C. Independent guava eval (Mendeley w3fg8jjmzr, Larkana PK, studio single-fruit, 270 images = 30 per variety x maturity; image level; ONNX 480 CPU; conf 0.35)", "",
      "| model | guava box present [95% CI] | top box is guava [95% CI] | no detection | top class when not guava |", "|---|---|---|---|---|"]
for f in sorted(glob.glob(f"{R}/guava_independent/*.json")):
    d = json.load(open(f))
    for m, v in d["models"].items():
        o.append(f"| {m} | {v['hit_rate']} {v['hit_ci95']} | {v['top_is_guava']} {v['top_ci95']} | {v['no_detection']} | {v['top_class_when_not_guava']} |")
o.append("")
# 4 size buckets
o += ["## D. Tiny objects: size-bucketed recall on locked test (n=557), conf 0.25, IoU 0.5, sandbox CPU PyTorch, batch 1", ""]
for f in sorted(glob.glob(f"{R}/size_buckets/*.json")):
    d = json.load(open(f)); o += [f"**{os.path.basename(f)[:-5]}** ({d['model'].split('/')[-4] if d['model'].count('/') > 3 else d['model']})", "",
                                  "| mode | <6 px | 6-12 | 12-24 | 24-48 | >=48 | recall all (cls) | precision | latency p50 / p90 ms |", "|---|---|---|---|---|---|---|---|---|"]
    for mode, v in d["modes"].items():
        b = v["buckets"]
        o.append(f"| {mode} | " + " | ".join(f"{b[k]['recall_cls']} (n={b[k]['n_gt']})" for k in ["<6", "6-12", "12-24", "24-48", ">=48"]) + f" | {v['recall_cls_all']} | {v['precision_cls']} | {v['latency_ms_p50']} / {v['latency_ms_p90']} |")
    o.append("")
# 5 citrus hierarchy
C = J("citrus_hierarchy.json")
o += ["## E. Citrus: hierarchical (generic 'citrus' unless subtype confident) vs flat, test_oiv7c (n=181 img), ONNX 480 CPU, conf 0.35; tau picked on OIV7c val", ""]
if C:
    o += ["| model | tau (val) | flat: lemon wrong-rate / citrus wrong-rate / pooled subtype precision | hier: coverage / subtype precision / wrong boxes (flat wrong) | lemon family recall |", "|---|---|---|---|---|"]
    for m, v in C["models"].items():
        f, h = v["flat"], v["hierarchical"]
        o.append(f"| {m} | {v['picked_tau']} | {f['lemon_lime']['wrong_rate_of_family']} / {f['citrus']['wrong_rate_of_family']} / {f['pooled']['subtype_precision']} | " +
                 (f"{h['pooled']['coverage']} / {h['pooled']['subtype_precision']} / {h['pooled']['wrong']} ({f['pooled']['wrong']})" if h else "-") + f" | {f['lemon_lime']['family_recall']} |")
else:
    o.append("pending")
o.append("")
# 6 tracking
o += ["## F. Tracking (G1 TEST synthetic clips, G3 det ONNX raw 480 + E224 T=0.25, sandbox CPU, fixed-frame)", "",
      "| run | det seg acc (n seg) | frame acc | TTFC p50/p90 ms | ID sw | fragmentations | missed s (frac) | longest gap s | static flicker /10s | neg FA/min | wall s |", "|---|---|---|---|---|---|---|---|---|---|---|"]
for d in sorted(glob.glob(f"{R}/tracking/*/gauntlet.json")) + sorted(glob.glob(f"{R}/tracking/tune/*/gauntlet.json")):
    g = json.load(open(d)); c = g["clips"].get("det"); n = g["clips"].get("neg", {})
    name = d.split("/tracking/")[1][:-14]
    if c:
        o.append(f"| {name} | {c['segment_acc']} ({c['segments']}) | {c['frame_acc']} | {c['ttfc_ms'].get('p50')}/{c['ttfc_ms'].get('p90')} | {c['id_switches']} | {c.get('fragmentations')} | {c.get('missed_s_total')} ({c.get('missed_frac')}) | {c.get('longest_missed_gap_s')} | {c['label_flicker_per_10s_static']} | {n.get('false_alarms_per_min', '-')} | {c.get('wall_s')} |")
    else:
        o.append(f"| {name} | - | - | - | - | - | - | - | - | {n.get('false_alarms_per_min', '-')} | {n.get('wall_s')} |")
P = J("tracking/tune/pick.json")
o += ["", f"DEV tuning pick (prereg addendum C): {P['pick'] if P else 'pending'}", ""]
# 7 hue shift
o += ["## G. Hue-shift sensitivity (OpenCV HSV hue rotation, S/V untouched; argmax decision)", ""]
for f in sorted(glob.glob(f"{R}/hue_shift/*.json")):
    d = json.load(open(f)); o += [f"**{os.path.basename(f)[:-5]}** (n={d.get('n', d['rows'][0].get('n_all'))}, {d.get('device', '')})", ""]
    ks = [k for k in d["rows"][0] if k not in ("hue_shift_deg",)]
    o += ["| hue shift deg | " + " | ".join(ks) + " |", "|---" * (len(ks) + 1) + "|"]
    for r in d["rows"]:
        o.append(f"| {r['hue_shift_deg']} | " + " | ".join(str(r[k]) for k in ks) + " |")
    o.append("")
# 8 autolabel
S = J("autolabel/summary.json")
o += ["## H. Auto-labelling (Phase 3) - PROPOSED labels only", "", json.dumps(S, indent=1) if S else "pending", ""]
V = J("video_v7/splits_v7_summary.json")
o += ["## I. Web-video counts and splits v7", "", json.dumps(V, indent=1) if V else "pending", ""]
PV = J("/workspace/work/nutrisole/ml/data/builds/v7/train_pool_v7_summary.json")
o += ["## J. train_pool_v7", "", json.dumps(PV["sources"], indent=1) if PV else "pending", ""]
open(OUT, "w").write("\n".join(o) + "\n"); print("wrote", OUT, len(o))
